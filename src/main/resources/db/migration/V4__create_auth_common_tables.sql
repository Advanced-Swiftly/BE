-- Issue #19 공통·인증 API에서 사용하는 회원, 인증, 기준정보 schema.

CREATE TABLE app_user (
    user_id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number   VARCHAR(20)  NOT NULL UNIQUE,
    password_hash  VARCHAR(100) NOT NULL,
    name           VARCHAR(50)  NOT NULL,
    role           VARCHAR(20)  NOT NULL,
    status         VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_app_user_role CHECK (role IN ('GUARDIAN', 'BUSINESS', 'OPERATOR')),
    CONSTRAINT chk_app_user_status CHECK (status IN ('ACTIVE', 'SUSPENDED', 'WITHDRAWN'))
);

CREATE TABLE refresh_token (
    refresh_token_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          BIGINT       NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    token_hash       VARCHAR(64)  NOT NULL UNIQUE,
    device_token     VARCHAR(255),
    expires_at       TIMESTAMPTZ  NOT NULL,
    revoked_at       TIMESTAMPTZ,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX idx_refresh_token_user ON refresh_token (user_id, created_at DESC);
CREATE INDEX idx_refresh_token_expiry ON refresh_token (expires_at) WHERE revoked_at IS NULL;

CREATE TABLE phone_verification (
    verification_id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    phone_number             VARCHAR(20)  NOT NULL,
    purpose                  VARCHAR(30)  NOT NULL,
    code_hash                VARCHAR(100) NOT NULL,
    expires_at               TIMESTAMPTZ  NOT NULL,
    attempt_count            INTEGER      NOT NULL DEFAULT 0,
    verified_at              TIMESTAMPTZ,
    verification_token_hash  VARCHAR(64),
    token_expires_at         TIMESTAMPTZ,
    consumed_at              TIMESTAMPTZ,
    created_at               TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_phone_verification_purpose
        CHECK (purpose IN ('SIGN_UP', 'LOGIN', 'CHANGE_PHONE')),
    CONSTRAINT chk_phone_verification_attempt_count CHECK (attempt_count >= 0)
);

CREATE INDEX idx_phone_verification_phone_created
    ON phone_verification (phone_number, created_at DESC);
CREATE UNIQUE INDEX uq_phone_verification_token
    ON phone_verification (verification_token_hash)
    WHERE verification_token_hash IS NOT NULL;

CREATE TABLE term (
    term_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role         VARCHAR(20)  NOT NULL,
    title        VARCHAR(100) NOT NULL,
    required     BOOLEAN      NOT NULL,
    version      VARCHAR(20)  NOT NULL,
    active       BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_term_role CHECK (role IN ('GUARDIAN', 'BUSINESS')),
    CONSTRAINT uq_term_role_title_version UNIQUE (role, title, version)
);

CREATE TABLE user_term_agreement (
    user_term_agreement_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id                BIGINT      NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    term_id                BIGINT      NOT NULL REFERENCES term (term_id),
    agreed                 BOOLEAN     NOT NULL,
    agreed_at              TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_user_term_agreement UNIQUE (user_id, term_id)
);

CREATE TABLE region (
    region_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_region_id  BIGINT REFERENCES region (region_id),
    name              VARCHAR(100) NOT NULL,
    active            BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_region_parent_name UNIQUE (parent_region_id, name)
);

CREATE INDEX idx_region_parent ON region (parent_region_id, name);

CREATE TABLE breed (
    breed_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100) NOT NULL UNIQUE,
    active    BOOLEAN      NOT NULL DEFAULT TRUE
);

