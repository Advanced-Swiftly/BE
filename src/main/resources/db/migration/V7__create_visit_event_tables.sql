CREATE TABLE stamp_event (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(150) NOT NULL,
    event_year INTEGER NOT NULL,
    quarter INTEGER NOT NULL,
    status VARCHAR(20) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    required_stamp_count INTEGER NOT NULL,
    max_stamp_count INTEGER NOT NULL,
    notice VARCHAR(2000),
    CONSTRAINT chk_stamp_event_quarter CHECK (quarter BETWEEN 1 AND 4),
    CONSTRAINT chk_stamp_event_status CHECK (status IN ('OPEN', 'CLOSED')),
    CONSTRAINT chk_stamp_event_period CHECK (starts_on <= ends_on),
    CONSTRAINT chk_stamp_event_counts CHECK (
        required_stamp_count > 0 AND max_stamp_count >= required_stamp_count
    )
);

CREATE TABLE event_region (
    event_id BIGINT NOT NULL REFERENCES stamp_event (event_id) ON DELETE CASCADE,
    region_id BIGINT NOT NULL REFERENCES region (region_id),
    PRIMARY KEY (event_id, region_id)
);

CREATE TABLE event_prize (
    prize_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES stamp_event (event_id) ON DELETE CASCADE,
    prize_rank INTEGER NOT NULL,
    name VARCHAR(150) NOT NULL,
    quantity INTEGER NOT NULL,
    CONSTRAINT uq_event_prize_rank UNIQUE (event_id, prize_rank),
    CONSTRAINT chk_event_prize_quantity CHECK (quantity > 0)
);

CREATE TABLE event_store (
    store_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES stamp_event (event_id) ON DELETE CASCADE,
    region_id BIGINT NOT NULL REFERENCES region (region_id),
    name VARCHAR(150) NOT NULL,
    latitude NUMERIC(10, 7),
    longitude NUMERIC(10, 7),
    approved BOOLEAN NOT NULL DEFAULT TRUE,
    qr_token_hash VARCHAR(64) NOT NULL UNIQUE,
    qr_expires_at TIMESTAMPTZ NOT NULL,
    qr_revoked BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT chk_event_store_latitude CHECK (latitude IS NULL OR latitude BETWEEN -90 AND 90),
    CONSTRAINT chk_event_store_longitude CHECK (longitude IS NULL OR longitude BETWEEN -180 AND 180)
);

CREATE INDEX idx_event_store_event_region ON event_store (event_id, region_id, approved);

CREATE TABLE visit (
    visit_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    store_id BIGINT NOT NULL REFERENCES event_store (store_id),
    qr_token_hash VARCHAR(64) NOT NULL,
    visited_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_visit_user_qr UNIQUE (user_id, qr_token_hash)
);

CREATE INDEX idx_visit_user_time ON visit (user_id, visited_at DESC);

CREATE TABLE visit_dog (
    visit_id BIGINT NOT NULL REFERENCES visit (visit_id) ON DELETE CASCADE,
    dog_id BIGINT NOT NULL REFERENCES dog (dog_id),
    PRIMARY KEY (visit_id, dog_id)
);

CREATE TABLE event_stamp (
    stamp_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES stamp_event (event_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    store_id BIGINT NOT NULL REFERENCES event_store (store_id),
    awarded_at TIMESTAMPTZ NOT NULL,
    CONSTRAINT uq_event_stamp_user_store UNIQUE (event_id, user_id, store_id)
);

CREATE INDEX idx_event_stamp_event_user ON event_stamp (event_id, user_id);

CREATE TABLE draw_entry (
    draw_entry_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id BIGINT NOT NULL REFERENCES stamp_event (event_id) ON DELETE CASCADE,
    user_id BIGINT NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    phone_number VARCHAR(20) NOT NULL,
    address VARCHAR(300) NOT NULL,
    privacy_agreed BOOLEAN NOT NULL,
    status VARCHAR(30) NOT NULL DEFAULT 'ENTERED',
    prize_id BIGINT REFERENCES event_prize (prize_id),
    fulfillment_status VARCHAR(30),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_draw_entry_event_user UNIQUE (event_id, user_id),
    CONSTRAINT chk_draw_entry_status CHECK (status IN ('ENTERED', 'WON', 'NOT_SELECTED')),
    CONSTRAINT chk_draw_fulfillment_status CHECK (
        fulfillment_status IS NULL OR fulfillment_status IN ('CONTACT_PENDING', 'PREPARING', 'SHIPPED', 'COMPLETED')
    )
);

