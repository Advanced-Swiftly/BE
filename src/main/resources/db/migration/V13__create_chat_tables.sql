CREATE TABLE chat_session (
    session_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id) ON DELETE CASCADE,
    title VARCHAR(100) NOT NULL,
    last_message_at TIMESTAMP WITH TIME ZONE,
    revision BIGINT NOT NULL DEFAULT 0
);
CREATE INDEX idx_chat_session_owner ON chat_session(user_id, last_message_at DESC NULLS LAST, session_id DESC);

CREATE TABLE chat_message (
    message_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id BIGINT NOT NULL REFERENCES chat_session(session_id) ON DELETE CASCADE,
    role VARCHAR(10) NOT NULL CHECK (role IN ('USER', 'ASSISTANT')),
    content VARCHAR(4000) NOT NULL,
    places_json TEXT NOT NULL
);
CREATE INDEX idx_chat_message_session ON chat_message(session_id, message_id DESC);

ALTER TABLE chat_session ENABLE ROW LEVEL SECURITY;
ALTER TABLE chat_message ENABLE ROW LEVEL SECURITY;
