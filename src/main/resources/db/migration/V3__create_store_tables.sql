-- 업체 인증 요청(POST /api/v1/business/verifications)에 필요한 최소 테이블.
-- users, region 테이블은 다른 담당자의 migration에서 만들어지므로 참조 컬럼은 FK 없이 둔다.
-- (submitted_by, reviewed_by -> users.user_id FK는 users migration 이후 별도 migration으로 추가)

CREATE TABLE store (
    store_id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                VARCHAR(100)  NOT NULL,
    phone               VARCHAR(20),
    address             VARCHAR(255)  NOT NULL,
    latitude            NUMERIC(10,7) NOT NULL,
    longitude           NUMERIC(10,7) NOT NULL,
    verification_status VARCHAR(20)   NOT NULL DEFAULT 'UNVERIFIED',
    created_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_store_verification_status
        CHECK (verification_status IN ('UNVERIFIED', 'PENDING', 'VERIFIED', 'REJECTED')),
    CONSTRAINT chk_store_latitude  CHECK (latitude  BETWEEN -90  AND 90),
    CONSTRAINT chk_store_longitude CHECK (longitude BETWEEN -180 AND 180)
);

CREATE TABLE store_verification (
    verification_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id            BIGINT       NOT NULL REFERENCES store (store_id) ON DELETE CASCADE,
    submitted_by        BIGINT       NOT NULL,
    business_number     VARCHAR(10)  NOT NULL,
    business_name       VARCHAR(100) NOT NULL,
    representative_name VARCHAR(50)  NOT NULL,
    document_url        VARCHAR(500) NOT NULL,
    status              VARCHAR(20)  NOT NULL DEFAULT 'RECEIVED',
    review_note         VARCHAR(500),
    reviewed_by         BIGINT,
    reviewed_at         TIMESTAMPTZ,
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_store_verification_request_status
        CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'NEEDS_SUPPLEMENT', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_store_verification_submitter ON store_verification (submitted_by, created_at DESC);
CREATE INDEX idx_store_verification_status ON store_verification (status, created_at);
CREATE INDEX idx_store_verification_store ON store_verification (store_id);

-- 반려(REJECTED)되지 않은 요청이 있는 사업자등록번호는 중복 요청 불가 (동시 요청 방어)
CREATE UNIQUE INDEX uq_store_verification_active_business_number
    ON store_verification (business_number)
    WHERE status <> 'REJECTED';
