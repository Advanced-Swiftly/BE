ALTER TABLE store ADD COLUMN region_id BIGINT REFERENCES region(region_id);
ALTER TABLE store ADD COLUMN category VARCHAR(80);

CREATE TABLE public_facility (
    facility_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(255),
    region_id BIGINT REFERENCES region(region_id),
    category VARCHAR(80),
    latitude NUMERIC(10,7) NOT NULL CHECK (latitude BETWEEN -90 AND 90),
    longitude NUMERIC(10,7) NOT NULL CHECK (longitude BETWEEN -180 AND 180),
    visible BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE TABLE place_entry_policy (
    place_id VARCHAR(32) PRIMARY KEY,
    pets_allowed BOOLEAN NOT NULL,
    max_weight_kg NUMERIC(6,2) CHECK (max_weight_kg > 0),
    source_text VARCHAR(2000) NOT NULL,
    confirmed_on DATE NOT NULL
);

CREATE TABLE place_entry_rule (
    place_id VARCHAR(32) NOT NULL REFERENCES place_entry_policy(place_id) ON DELETE CASCADE,
    rule_type VARCHAR(20) NOT NULL CHECK (rule_type IN ('BREED_DENIED', 'EQUIPMENT', 'VACCINE')),
    rule_code VARCHAR(80) NOT NULL,
    PRIMARY KEY (place_id, rule_type, rule_code)
);

CREATE VIEW place_catalog AS
SELECT CONCAT('STORE:', store_id) AS place_id, name, address, region_id, category, latitude, longitude
FROM store WHERE verification_status = 'VERIFIED'
UNION ALL
SELECT CONCAT('PUBLIC:', facility_id), name, address, region_id, category, latitude, longitude
FROM public_facility WHERE visible = TRUE;
