-- Issue #16 반려견 API에서 사용하는 반려견과 보유 장비 schema.

CREATE TABLE dog (
    dog_id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id              BIGINT         NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    breed_id             BIGINT         NOT NULL REFERENCES breed (breed_id),
    name                 VARCHAR(50)    NOT NULL,
    birth_date           DATE,
    weight_kg            NUMERIC(6, 2),
    is_default           BOOLEAN        NOT NULL DEFAULT FALSE,
    vaccination_status   VARCHAR(30)    NOT NULL DEFAULT 'NOT_SUBMITTED',
    created_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ    NOT NULL DEFAULT now(),
    CONSTRAINT chk_dog_weight CHECK (weight_kg IS NULL OR weight_kg > 0),
    CONSTRAINT chk_dog_vaccination_status CHECK (
        vaccination_status IN ('NOT_SUBMITTED', 'PENDING', 'VERIFIED', 'REJECTED', 'NEEDS_MANUAL_REVIEW')
    )
);

CREATE INDEX idx_dog_user_created ON dog (user_id, created_at, dog_id);
CREATE UNIQUE INDEX uq_dog_user_default ON dog (user_id) WHERE is_default = TRUE;

CREATE TABLE dog_equipment (
    dog_id          BIGINT      NOT NULL REFERENCES dog (dog_id) ON DELETE CASCADE,
    equipment_code VARCHAR(50) NOT NULL,
    PRIMARY KEY (dog_id, equipment_code)
);
