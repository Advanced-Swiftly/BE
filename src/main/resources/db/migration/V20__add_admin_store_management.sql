-- Issue #52 운영자 업체 관리·사업자 인증 심사·이벤트 추첨 지원.

-- 업체 노출 상태. 기존 업체는 모두 노출 상태로 둔다.
ALTER TABLE store ADD COLUMN visibility VARCHAR(10) NOT NULL DEFAULT 'VISIBLE';
ALTER TABLE store ADD CONSTRAINT chk_store_visibility CHECK (visibility IN ('VISIBLE', 'HIDDEN'));

-- 업체와 업체 관리자의 연결. 업체당 관리자는 한 명이다.
CREATE TABLE store_manager (
    store_id    BIGINT       PRIMARY KEY REFERENCES store (store_id) ON DELETE CASCADE,
    user_id     BIGINT       NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_store_manager_user ON store_manager (user_id);

-- 이미 승인된 사업자 인증은 요청자를 업체 관리자로 옮긴다. (업체마다 가장 최근 승인 건)
INSERT INTO store_manager (store_id, user_id)
SELECT DISTINCT ON (store_id) store_id, submitted_by
FROM store_verification
WHERE status = 'APPROVED'
ORDER BY store_id, verification_id DESC;

-- 사업자 인증 심사 상태 이력.
CREATE TABLE store_verification_history (
    history_id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    verification_id  BIGINT       NOT NULL REFERENCES store_verification (verification_id) ON DELETE CASCADE,
    status           VARCHAR(20)  NOT NULL,
    comment          VARCHAR(500),
    changed_by       BIGINT,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE INDEX idx_store_verification_history ON store_verification_history (verification_id, history_id);

-- 입장 조건 요청 종류에 AI 후보와 운영자 재검토 요청을 추가한다.
ALTER TABLE condition_request DROP CONSTRAINT chk_condition_request_kind;
ALTER TABLE condition_request ADD CONSTRAINT chk_condition_request_kind
    CHECK (kind IN ('CONDITION_REQUEST', 'AI_CANDIDATE', 'OPERATOR_DIRECT', 'RECHECK'));

-- 이벤트 추첨 실행 기록. 이벤트당 한 번만 실행할 수 있다.
CREATE TABLE event_draw (
    event_id      BIGINT       PRIMARY KEY REFERENCES stamp_event (event_id) ON DELETE CASCADE,
    drawn_at      TIMESTAMPTZ  NOT NULL,
    seed          VARCHAR(100) NOT NULL,
    winner_count  INTEGER      NOT NULL,
    executed_by   BIGINT,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 운영자가 숨긴 업체는 지도·검색(장소 카탈로그)에서 뺀다.
CREATE OR REPLACE VIEW place_catalog AS
SELECT CONCAT('STORE:', store_id) AS place_id, name, address, region_id, category, latitude, longitude
FROM store WHERE verification_status = 'VERIFIED' AND visibility = 'VISIBLE'
UNION ALL
SELECT CONCAT('PUBLIC:', facility_id), name, address, region_id, category, latitude, longitude
FROM public_facility WHERE visible = TRUE;
