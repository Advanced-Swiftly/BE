CREATE TABLE uploaded_asset (
    asset_id UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES app_user(user_id),
    storage_path VARCHAR(500) NOT NULL UNIQUE,
    content_type VARCHAR(80) NOT NULL,
    original_name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE TABLE store_image (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id BIGINT NOT NULL REFERENCES store(store_id) ON DELETE CASCADE,
    asset_id UUID NOT NULL REFERENCES uploaded_asset(asset_id),
    display_order INTEGER NOT NULL DEFAULT 0
);
CREATE TABLE public_facility_image (
    image_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    facility_id BIGINT NOT NULL REFERENCES public_facility(facility_id) ON DELETE CASCADE,
    image_url VARCHAR(2000) NOT NULL,
    UNIQUE (facility_id, image_url)
);
