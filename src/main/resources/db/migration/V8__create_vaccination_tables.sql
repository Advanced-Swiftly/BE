CREATE TABLE vaccination_record (
    record_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dog_id BIGINT NOT NULL UNIQUE REFERENCES dog(dog_id) ON DELETE CASCADE,
    status VARCHAR(30) NOT NULL,
    revision INTEGER NOT NULL DEFAULT 1
);
CREATE TABLE vaccination_document (
    document_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id BIGINT NOT NULL REFERENCES vaccination_record(record_id) ON DELETE CASCADE,
    object_path VARCHAR(300) NOT NULL
);
CREATE TABLE vaccination_item (
    item_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    record_id BIGINT NOT NULL REFERENCES vaccination_record(record_id) ON DELETE CASCADE,
    source VARCHAR(10) NOT NULL CHECK (source IN ('AI', 'GUARDIAN', 'OPERATOR')),
    vaccine_code VARCHAR(80) NOT NULL,
    vaccinated_at DATE NOT NULL,
    confidence DOUBLE PRECISION
);
CREATE INDEX idx_vaccination_document_record ON vaccination_document(record_id);
CREATE INDEX idx_vaccination_item_record ON vaccination_item(record_id);
ALTER TABLE vaccination_record ENABLE ROW LEVEL SECURITY;
ALTER TABLE vaccination_document ENABLE ROW LEVEL SECURITY;
ALTER TABLE vaccination_item ENABLE ROW LEVEL SECURITY;
