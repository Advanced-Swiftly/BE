-- Issue #42 업체 신청(이벤트 참여·광고 노출) API 테이블.
-- submitted_by, reviewed_by -> app_user.user_id FK는 업체 인증 테이블과 같이 운영자 심사 작업에서 추가한다.

CREATE TABLE event_application (
    application_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT       NOT NULL REFERENCES store (store_id),
    event_id        BIGINT       NOT NULL REFERENCES stamp_event (event_id),
    submitted_by    BIGINT       NOT NULL,
    message         VARCHAR(500),
    status          VARCHAR(20)  NOT NULL DEFAULT 'RECEIVED',
    review_note     VARCHAR(500),
    reviewed_by     BIGINT,
    reviewed_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_event_application_status
        CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'APPROVED', 'REJECTED', 'CANCELED'))
);

-- 같은 업체가 같은 이벤트에 진행 중(반려·취소되지 않은) 신청을 중복해서 둘 수 없다.
CREATE UNIQUE INDEX uq_event_application_active
    ON event_application (store_id, event_id)
    WHERE status NOT IN ('REJECTED', 'CANCELED');

CREATE INDEX idx_event_application_submitted_by ON event_application (submitted_by, application_id DESC);

CREATE TABLE event_application_region (
    application_id  BIGINT NOT NULL REFERENCES event_application (application_id) ON DELETE CASCADE,
    region_id       BIGINT NOT NULL REFERENCES region (region_id),
    PRIMARY KEY (application_id, region_id)
);

CREATE TABLE ad_application (
    application_id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        BIGINT       NOT NULL REFERENCES store (store_id),
    submitted_by    BIGINT       NOT NULL,
    ad_type         VARCHAR(20)  NOT NULL,
    start_date      DATE         NOT NULL,
    end_date        DATE         NOT NULL,
    creative_url    VARCHAR(500) NOT NULL,
    message         VARCHAR(500),
    status          VARCHAR(20)  NOT NULL DEFAULT 'RECEIVED',
    review_note     VARCHAR(500),
    reviewed_by     BIGINT,
    reviewed_at     TIMESTAMPTZ,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_ad_application_type CHECK (ad_type IN ('BANNER', 'RECOMMENDED')),
    CONSTRAINT chk_ad_application_period CHECK (start_date <= end_date),
    CONSTRAINT chk_ad_application_status
        CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'APPROVED', 'REJECTED', 'CANCELED'))
);

CREATE INDEX idx_ad_application_submitted_by ON ad_application (submitted_by, application_id DESC);
