-- Issue #44 업체 운영 API(기본 정보·입장 정책·조건 변경 요청·QR) 테이블.
-- submitted_by, reviewed_by -> app_user.user_id FK는 업체 인증 테이블과 같이 운영자 심사 작업에서 추가한다.

ALTER TABLE store ADD COLUMN description VARCHAR(1000);

CREATE TABLE store_amenity (
    store_id      BIGINT      NOT NULL REFERENCES store (store_id) ON DELETE CASCADE,
    amenity_code  VARCHAR(50) NOT NULL,
    PRIMARY KEY (store_id, amenity_code)
);

-- 업체 입장 정책. 승인된 변경이 반영될 때마다 version이 1씩 올라간 새 행이 생기고, 가장 큰 version이 현재 정책이다.
CREATE TABLE store_policy (
    policy_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id     BIGINT        NOT NULL REFERENCES store (store_id) ON DELETE CASCADE,
    version      INTEGER       NOT NULL,
    source_text  VARCHAR(2000),
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT uq_store_policy_version UNIQUE (store_id, version),
    CONSTRAINT chk_store_policy_version CHECK (version >= 1)
);

CREATE TABLE store_policy_rule (
    policy_id      BIGINT      NOT NULL REFERENCES store_policy (policy_id) ON DELETE CASCADE,
    rule_type      VARCHAR(20) NOT NULL,
    rule_code      VARCHAR(80) NOT NULL,
    rule_required  BOOLEAN     NOT NULL DEFAULT TRUE,
    PRIMARY KEY (policy_id, rule_type, rule_code),
    CONSTRAINT chk_store_policy_rule_type CHECK (rule_type IN ('BREED', 'EQUIPMENT', 'VACCINE'))
);

CREATE TABLE condition_request (
    request_id    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id      BIGINT        NOT NULL REFERENCES store (store_id) ON DELETE CASCADE,
    base_version  INTEGER       NOT NULL,
    source_text   VARCHAR(2000) NOT NULL,
    submitted_by  BIGINT        NOT NULL,
    status        VARCHAR(20)   NOT NULL DEFAULT 'RECEIVED',
    review_note   VARCHAR(500),
    reviewed_by   BIGINT,
    reviewed_at   TIMESTAMPTZ,
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_condition_request_base_version CHECK (base_version >= 0),
    CONSTRAINT chk_condition_request_status
        CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'NEEDS_SUPPLEMENT', 'APPROVED', 'REJECTED'))
);

CREATE INDEX idx_condition_request_submitted_by ON condition_request (submitted_by, request_id DESC);

CREATE TABLE condition_request_rule (
    request_id     BIGINT      NOT NULL REFERENCES condition_request (request_id) ON DELETE CASCADE,
    rule_type      VARCHAR(20) NOT NULL,
    rule_code      VARCHAR(80) NOT NULL,
    rule_required  BOOLEAN     NOT NULL DEFAULT TRUE,
    PRIMARY KEY (request_id, rule_type, rule_code),
    CONSTRAINT chk_condition_request_rule_type CHECK (rule_type IN ('BREED', 'EQUIPMENT', 'VACCINE'))
);

CREATE TABLE condition_request_evidence (
    request_id    BIGINT       NOT NULL REFERENCES condition_request (request_id) ON DELETE CASCADE,
    evidence_url  VARCHAR(500) NOT NULL,
    PRIMARY KEY (request_id, evidence_url)
);

-- 업체 QR. 가장 최근에 발급된 행이 현재 QR이다. 발급은 업체 승인(운영자 심사) 작업에서 한다.
CREATE TABLE store_qr (
    qr_id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id      BIGINT       NOT NULL REFERENCES store (store_id) ON DELETE CASCADE,
    status        VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE',
    qr_image_url  VARCHAR(500) NOT NULL,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT chk_store_qr_status CHECK (status IN ('ACTIVE', 'DISABLED'))
);

CREATE INDEX idx_store_qr_store ON store_qr (store_id, qr_id DESC);
