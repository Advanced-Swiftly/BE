-- Issue #12 사용자의 1:1 문의 등록·조회에 필요한 schema.

CREATE TABLE inquiry (
    inquiry_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT        NOT NULL REFERENCES app_user (user_id) ON DELETE CASCADE,
    category     VARCHAR(20)   NOT NULL,
    title        VARCHAR(100)  NOT NULL,
    content      VARCHAR(4000) NOT NULL,
    status       VARCHAR(20)   NOT NULL DEFAULT 'WAITING',
    answer       VARCHAR(4000),
    answered_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT chk_inquiry_category
        CHECK (category IN ('ACCOUNT', 'PLACE', 'EVENT', 'ETC')),
    CONSTRAINT chk_inquiry_status
        CHECK (status IN ('WAITING', 'ANSWERED'))
);

CREATE INDEX idx_inquiry_user_created
    ON inquiry (user_id, created_at DESC);
CREATE INDEX idx_inquiry_user_status_created
    ON inquiry (user_id, status, created_at DESC);

CREATE TABLE inquiry_attachment (
    inquiry_attachment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id            BIGINT       NOT NULL REFERENCES inquiry (inquiry_id) ON DELETE CASCADE,
    attachment_url        VARCHAR(500) NOT NULL,
    display_order         INTEGER      NOT NULL,
    CONSTRAINT chk_inquiry_attachment_order CHECK (display_order >= 0),
    CONSTRAINT uq_inquiry_attachment_order UNIQUE (inquiry_id, display_order)
);

CREATE INDEX idx_inquiry_attachment_inquiry
    ON inquiry_attachment (inquiry_id, display_order);
