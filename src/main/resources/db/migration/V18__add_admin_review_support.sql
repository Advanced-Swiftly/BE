-- Issue #48 운영자 심사 API 지원.

-- 신청 심사에 보완 요청(NEEDS_INFO) 상태를 추가한다.
ALTER TABLE event_application DROP CONSTRAINT chk_event_application_status;
ALTER TABLE event_application ADD CONSTRAINT chk_event_application_status
    CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'NEEDS_INFO', 'APPROVED', 'REJECTED', 'CANCELED'));

ALTER TABLE ad_application DROP CONSTRAINT chk_ad_application_status;
ALTER TABLE ad_application ADD CONSTRAINT chk_ad_application_status
    CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'NEEDS_INFO', 'APPROVED', 'REJECTED', 'CANCELED'));

-- 정책 변경 이력: 누가(changed_by) 어떤 요청(request_id)으로 바꿨는지. 기존 행은 비어 있다.
ALTER TABLE store_policy ADD COLUMN changed_by VARCHAR(20);
ALTER TABLE store_policy ADD COLUMN request_id BIGINT REFERENCES condition_request (request_id) ON DELETE SET NULL;

-- 당첨 취소를 나타내는 CANCELED 상태 추가.
ALTER TABLE draw_entry DROP CONSTRAINT chk_draw_entry_status;
ALTER TABLE draw_entry ADD CONSTRAINT chk_draw_entry_status
    CHECK (status IN ('ENTERED', 'WON', 'NOT_SELECTED', 'CANCELED'));

-- 당첨·배송 처리에서 운영자가 남기는 값(주소 확인 여부, 운송장, 메모).
CREATE TABLE draw_entry_fulfillment (
    draw_entry_id      BIGINT       PRIMARY KEY REFERENCES draw_entry (draw_entry_id) ON DELETE CASCADE,
    address_confirmed  BOOLEAN      NOT NULL DEFAULT FALSE,
    tracking_number    VARCHAR(50),
    note               VARCHAR(500),
    updated_by         BIGINT,
    created_at         TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ  NOT NULL DEFAULT now()
);

-- 문의 답변에 붙는 첨부파일.
CREATE TABLE inquiry_answer_attachment (
    attachment_id   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    inquiry_id      BIGINT       NOT NULL REFERENCES inquiry (inquiry_id) ON DELETE CASCADE,
    attachment_url  VARCHAR(500) NOT NULL,
    display_order   INTEGER      NOT NULL,
    CONSTRAINT chk_inquiry_answer_attachment_order CHECK (display_order >= 0),
    CONSTRAINT uq_inquiry_answer_attachment_order UNIQUE (inquiry_id, display_order)
);
