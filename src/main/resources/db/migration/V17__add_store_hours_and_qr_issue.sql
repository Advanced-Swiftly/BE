-- Issue #46 업체 운영 API(영업시간·입장 조건 요청 취소/보완·QR 발급).
-- 이미 병합된 V16은 수정하지 않고 필요한 변경을 여기서 한다.

-- 입장 조건 요청 취소(CANCELED) 상태 추가
ALTER TABLE condition_request DROP CONSTRAINT chk_condition_request_status;
ALTER TABLE condition_request ADD CONSTRAINT chk_condition_request_status
    CHECK (status IN ('RECEIVED', 'IN_REVIEW', 'NEEDS_SUPPLEMENT', 'APPROVED', 'REJECTED', 'CANCELED'));

-- 업체 QR 재발급 시 기존 QR을 폐기(REVOKED)하고, 방문 인증에 쓰는 토큰을 저장한다.
ALTER TABLE store_qr DROP CONSTRAINT chk_store_qr_status;
ALTER TABLE store_qr ADD CONSTRAINT chk_store_qr_status CHECK (status IN ('ACTIVE', 'DISABLED', 'REVOKED'));
ALTER TABLE store_qr ADD COLUMN qr_token VARCHAR(64);
ALTER TABLE store_qr ADD COLUMN qr_token_hash VARCHAR(64) UNIQUE;
ALTER TABLE store_qr ADD COLUMN issue_reason VARCHAR(200);

CREATE TABLE store_business_hours (
    hours_id     BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id     BIGINT      NOT NULL REFERENCES store (store_id) ON DELETE CASCADE,
    day_of_week  VARCHAR(10) NOT NULL,
    open_time    TIME,
    close_time   TIME,
    closed       BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_store_business_hours_day UNIQUE (store_id, day_of_week),
    CONSTRAINT chk_store_business_hours_day CHECK (day_of_week IN
        ('MONDAY', 'TUESDAY', 'WEDNESDAY', 'THURSDAY', 'FRIDAY', 'SATURDAY', 'SUNDAY')),
    CONSTRAINT chk_store_business_hours_time CHECK (
        closed OR (open_time IS NOT NULL AND close_time IS NOT NULL AND open_time < close_time))
);
