    @Test
    @WithMockUser(username = "9", roles = "OPERATOR")
    void rejectsInvalidAdReviewTransitions() throws Exception {
        Long received = saveAd(saveStore(), "RECEIVED");
        Long done = saveAd(saveStore(), "APPROVED");

        // 심사를 시작하지 않은 신청은 바로 승인할 수 없다.
        mockMvc.perform(patch(BASE + "/ad-applications/" + received)
                        .contentType(MediaType.APPLICATION_JSON).content(review("APPROVE", null)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("INVALID_REQUEST_STATE"));
        // 끝난 신청은 다시 처리할 수 없다.
        mockMvc.perform(patch(BASE + "/ad-applications/" + done)
                        .contentType(MediaType.APPLICATION_JSON).content(review("START_REVIEW", null)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("INVALID_REQUEST_STATE"));
        // 보완·반려 사유가 없으면 400
        Long reviewing = saveAd(saveStore(), "IN_REVIEW");
        mockMvc.perform(patch(BASE + "/ad-applications/" + reviewing)
                        .contentType(MediaType.APPLICATION_JSON).content(review("REJECT", null)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("COMMON_001"));
        mockMvc.perform(patch(BASE + "/ad-applications/" + reviewing)
                        .contentType(MediaType.APPLICATION_JSON).content("{}"))
                .andExpect(status().isBadRequest());
        mockMvc.perform(patch(BASE + "/ad-applications/" + reviewing)
                        .contentType(MediaType.APPLICATION_JSON).content(review("DELETE", null)))
                .andExpect(status().isBadRequest());
        mockMvc.perform(patch(BASE + "/ad-applications/999999")
                        .contentType(MediaType.APPLICATION_JSON).content(review("START_REVIEW", null)))
                .andExpect(status().isNotFound());
    }

