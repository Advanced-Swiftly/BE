    @Test
    @WithMockUser(username = "9", roles = "OPERATOR")
    void movesWinnerThroughFulfillmentSteps() throws Exception {
        insertEvent();
        Long id = insertDrawEntry(1L, "WON", "CONTACT_PENDING");
        String url = BASE + "/draw-entries/" + id;

        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON).content(act("CONTACTED", "\"note\": \"전화 완료\"")))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("WON"))
                .andExpect(jsonPath("$.fulfillmentStatus").value("PREPARING"));
        // 주소 확인 전 발송은 막힌다.
        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON)
                        .content(act("SHIPPED", "\"trackingNumber\": \"123\"")))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("INVALID_REQUEST_STATE"));
        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON).content(act("ADDRESS_CONFIRMED", null)))
                .andExpect(jsonPath("$.fulfillmentStatus").value("PREPARING"));
        // 운송장 없이 발송하면 400
        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON).content(act("SHIPPED", null)))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("COMMON_001"));
        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON)
                        .content(act("SHIPPED", "\"trackingNumber\": \"1234567890\"")))
                .andExpect(jsonPath("$.fulfillmentStatus").value("SHIPPED"));
        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON).content(act("DELIVERED", null)))
                .andExpect(jsonPath("$.status").value("WON"))
                .andExpect(jsonPath("$.fulfillmentStatus").value("COMPLETED"));

        assertThat(jdbcTemplate.queryForObject(
                        "select tracking_number from draw_entry_fulfillment where draw_entry_id = ?", String.class, id))
                .isEqualTo("1234567890");
        assertThat(jdbcTemplate.queryForObject(
                        "select note from draw_entry_fulfillment where draw_entry_id = ?", String.class, id))
                .isEqualTo("전화 완료");
    }

