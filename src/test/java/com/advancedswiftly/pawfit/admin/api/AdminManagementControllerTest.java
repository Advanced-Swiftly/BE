    @Test
    @WithMockUser(username = "9", roles = "OPERATOR")
    void reviewsAndApprovesConditionRequest() throws Exception {
        Store store = saveStore();
        policyRepository.save(StorePolicy.create(store.getId(), 1, "초기", List.of()));
        Long id = saveRequest(store, 1, "RECEIVED", List.of(carrier(true)));
        String url = BASE + "/condition-requests/" + id;

        // 접수 상태에서 바로 승인할 수는 없다.
        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"APPROVE\"}"))
                .andExpect(status().isBadRequest())
                .andExpect(jsonPath("$.code").value("INVALID_REQUEST_STATE"));
        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"START_REVIEW\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("IN_REVIEW"))
                .andExpect(jsonPath("$.appliedPolicyVersion").doesNotExist());
        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"REJECT\"}"))
                .andExpect(status().isBadRequest());
        mockMvc.perform(patch(url).contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"APPROVE\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("APPROVED"))
                .andExpect(jsonPath("$.appliedPolicyVersion").value(2));

        assertThat(jdbcTemplate.queryForObject(
                        "select count(*) from store_policy where store_id = ? and version = 2 and changed_by = 'OPERATOR'",
                        Long.class, store.getId()))
                .isEqualTo(1L);
        assertThat(jdbcTemplate.queryForObject(
                        "select count(*) from store_policy_rule r join store_policy p on p.policy_id = r.policy_id "
                                + "where p.version = 2 and r.rule_code = 'CARRIER'",
                        Long.class))
                .isEqualTo(1L);
    }

    @Test
    @WithMockUser(username = "9", roles = "OPERATOR")
    void needsInfoRequiresCommentAndStaleApprovalConflicts() throws Exception {
        Store store = saveStore();
        policyRepository.save(StorePolicy.create(store.getId(), 1, "초기", List.of()));
        Long stale = saveRequest(store, 0, "IN_REVIEW", List.of(carrier(true)));

        mockMvc.perform(patch(BASE + "/condition-requests/" + stale)
                        .contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"APPROVE\"}"))
                .andExpect(status().isConflict())
                .andExpect(jsonPath("$.code").value("POLICY_VERSION_CONFLICT"));
        mockMvc.perform(patch(BASE + "/condition-requests/" + stale)
                        .contentType(MediaType.APPLICATION_JSON).content("{\"action\":\"NEEDS_INFO\"}"))
                .andExpect(status().isBadRequest());
        mockMvc.perform(patch(BASE + "/condition-requests/" + stale)
                        .contentType(MediaType.APPLICATION_JSON)
                        .content("{\"action\":\"NEEDS_INFO\",\"reviewComment\":\"근거 추가\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("NEEDS_SUPPLEMENT"));
    }

    @Test
    @WithMockUser(username = "9", roles = "OPERATOR")
    void changesPolicyDirectly() throws Exception {
        Store store = saveStore();
        String body = """
                {"baseVersion":0,"policy":{"equipmentRules":[{"code":"CARRIER","required":true}]},
                 "sourceText":"현장 확인","reason":"전화 확인"}""";
        mockMvc.perform(post(BASE + "/stores/" + store.getId() + "/policy-changes")
                        .contentType(MediaType.APPLICATION_JSON).content(body))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.kind").value("OPERATOR_DIRECT"))
                .andExpect(jsonPath("$.status").value("APPROVED"))
                .andExpect(jsonPath("$.appliedPolicyVersion").value(1));
        // 같은 기준 버전으로 다시 보내면 이미 바뀐 정책이라 충돌.
        mockMvc.perform(post(BASE + "/stores/" + store.getId() + "/policy-changes")
                        .contentType(MediaType.APPLICATION_JSON).content(body))
                .andExpect(status().isConflict());
        mockMvc.perform(post(BASE + "/stores/9999/policy-changes")
                        .contentType(MediaType.APPLICATION_JSON).content(body))
                .andExpect(status().isNotFound());
        mockMvc.perform(post(BASE + "/stores/" + store.getId() + "/policy-changes")
                        .contentType(MediaType.APPLICATION_JSON).content("{\"baseVersion\":1}"))
                .andExpect(status().isBadRequest());
    }

