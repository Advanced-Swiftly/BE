    private PolicyRule carrier(boolean required) {
        return new PolicyRule(PolicyRuleType.EQUIPMENT, "CARRIER", required);
    }

    private Long saveRequest(Store store, int baseVersion, String status, List<PolicyRule> rules) {
        ConditionRequest request = conditionRequestRepository.save(
                ConditionRequest.receive(store.getId(), baseVersion, "원문", 1L, rules, List.of("https://e.com/1.pdf")));
        jdbcTemplate.update("update condition_request set status = ? where request_id = ?", status, request.getId());
        return request.getId();
    }

    private String eventJson(int quarter) {
        return """
                {"title":"스탬프 투어","year":2027,"quarter":%d,"startsOn":"2027-01-01","endsOn":"2027-03-31",
                 "requiredStampCount":3,"maxStampCount":5,"regionIds":[11],
                 "prizes":[{"rank":1,"name":"유모차","quantity":2}]}""".formatted(quarter);
    }

    private long createEvent(int quarter) throws Exception {
        String body = mockMvc.perform(post(BASE + "/events").contentType(MediaType.APPLICATION_JSON).content(eventJson(quarter)))
                .andExpect(status().isCreated())
                .andExpect(jsonPath("$.status").value("DRAFT"))
                .andReturn().getResponse().getContentAsString();
        return com.jayway.jsonpath.JsonPath.parse(body).read("$.eventId", Long.class);
    }

