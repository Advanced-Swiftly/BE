    void verifiesVaccinationWithOperatorItems() throws Exception {
        insertDog(5, "콩이");
        jdbcTemplate.update("insert into vaccination_record (record_id, dog_id, status) values (20, 5, 'NEEDS_MANUAL_REVIEW')");
        jdbcTemplate.update(
                "insert into vaccination_item (record_id, source, vaccine_code, vaccinated_at) values (20, 'OPERATOR', 'OLD', '2026-01-01')");

        mockMvc.perform(patch(BASE + "/vaccination-records/20").contentType(MediaType.APPLICATION_JSON)
                        .content("{\"action\":\"VERIFY\",\"items\":[{\"vaccineCode\":\"RABIES\",\"vaccinatedAt\":\"2026-05-10\"}]}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("VERIFIED"));

        assertThat(jdbcTemplate.queryForList(
                        "select vaccine_code from vaccination_item where record_id = 20 and source = 'OPERATOR'",
                        String.class))
                .containsExactly("RABIES");
        assertThat(jdbcTemplate.queryForObject("select vaccination_status from dog where dog_id = 5", String.class))
                .isEqualTo("VERIFIED");
    }
