    @Test
    @WithMockUser(username = "9", roles = "OPERATOR")
    void managesEventLifecycle() throws Exception {
        long eventId = createEvent(1);
        mockMvc.perform(post(BASE + "/events").contentType(MediaType.APPLICATION_JSON).content(eventJson(1)))
                .andExpect(status().isConflict())
                .andExpect(jsonPath("$.code").value("DUPLICATE_EVENT_PERIOD"));
        mockMvc.perform(post(BASE + "/events").contentType(MediaType.APPLICATION_JSON)
                        .content(eventJson(2).replace("[11]", "[999]")))
                .andExpect(status().isBadRequest());
        mockMvc.perform(post(BASE + "/events").contentType(MediaType.APPLICATION_JSON)
                        .content(eventJson(3).replace("\"quarter\":3", "\"quarter\":5")))
                .andExpect(status().isBadRequest());

        mockMvc.perform(get(BASE + "/events").param("year", "2027").param("status", "DRAFT"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.items.length()").value(1))
                .andExpect(jsonPath("$.items[0].eventId").value(eventId));
        mockMvc.perform(get(BASE + "/events").param("status", "BOGUS")).andExpect(status().isBadRequest());

        mockMvc.perform(patch(BASE + "/events/" + eventId).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"title\":\"새 제목\",\"prizes\":[{\"rank\":1,\"name\":\"가방\",\"quantity\":1},"
                                + "{\"rank\":2,\"name\":\"간식\",\"quantity\":5}],\"status\":\"OPEN\"}"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.status").value("OPEN"));
        assertThat(jdbcTemplate.queryForObject(
                        "select count(*) from event_prize where event_id = ?", Long.class, eventId))
                .isEqualTo(2L);

        mockMvc.perform(patch(BASE + "/events/" + eventId).contentType(MediaType.APPLICATION_JSON)
                        .content("{\"title\":\"또 수정\"}"))
                .andExpect(status().isConflict())
                .andExpect(jsonPath("$.code").value("EVENT_NOT_EDITABLE"));
        mockMvc.perform(delete(BASE + "/events/" + eventId))
                .andExpect(status().isConflict())
                .andExpect(jsonPath("$.code").value("EVENT_NOT_DELETABLE"));

        long draft = createEvent(2);
        mockMvc.perform(delete(BASE + "/events/" + draft)).andExpect(status().isNoContent());
        mockMvc.perform(delete(BASE + "/events/" + draft)).andExpect(status().isNotFound());
        assertThat(jdbcTemplate.queryForObject(
                        "select count(*) from event_region where event_id = ?", Long.class, draft))
                .isZero();
    }

